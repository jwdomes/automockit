package com.example.flowdocs.test;

import static org.junit.jupiter.api.Assertions.assertFalse;

import com.tngtech.archunit.core.domain.JavaClass;
import com.tngtech.archunit.core.domain.JavaClasses;
import java.io.IOException;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/** Snapshots flow.mmd (the static graph) and README.md (graph, steps and decisions, scenarios). */
public final class StaticFlowDocs {

    public static void verify(FlowDocsSettings settings) throws IOException {
        JavaClasses classes = settings.importClasses();
        Map<String, String> labels = FlowParticipants.labels(classes);
        FlowGraph graph = new FlowGraph(classes, settings.basePackage(), labels);
        assertFalse(graph.nodes().isEmpty(), "No @FlowStep or @FlowDecision methods under " + settings.basePackage());

        String mermaid = graph.mermaid();
        Snapshots.verifyOrUpdate(settings.docsDir().resolve("flow.mmd"), mermaid);
        Snapshots.verifyOrUpdate(settings.docsDir().resolve("README.md"), index(settings, graph, mermaid, labels));
    }

    private static String index(FlowDocsSettings settings, FlowGraph graph, String mermaid, Map<String, String> labels)
            throws IOException {
        StringBuilder sb = new StringBuilder("""
                # Flow docs

                Generated by the flow-docs tests. Don't edit by hand: run `./gradlew test -PupdateFlowDocs`
                and commit the result.

                ## Flow

                ```mermaid
                """).append(mermaid).append("""
                ```

                ## Steps and decisions

                | Name | Kind | Participant | Code |
                | --- | --- | --- | --- |
                """);
        Path sources = settings.docsDir().relativize(Path.of("src/main/java"));
        for (FlowGraph.Node n : graph.nodes()) {
            sb.append("| %s | %s | %s | %s |\n".formatted(n.text(), n.kind().name().toLowerCase(Locale.ROOT),
                    labels.getOrDefault(n.participant(), n.participant()), codeLink(sources, n)));
        }
        sb.append("""

                ## Scenarios

                | Scenario | Description | Request | Expected status |
                | --- | --- | --- | --- |
                """);
        List<String> names = Scenario.names(settings.scenariosDir()).toList();
        for (String name : names) {
            Scenario scenario = Scenario.load(settings.scenariosDir(), name);
            sb.append("| [%s](flows/%s.md) | %s | `%s %s` | %d |\n".formatted(name, name, scenario.description(),
                    scenario.method(), scenario.path(), scenario.expectedStatus()));
        }
        return sb.toString();
    }

    /** Class#method linking to the source file; no line numbers, so unrelated edits don't stale the doc. */
    private static String codeLink(Path sources, FlowGraph.Node n) {
        JavaClass owner = n.method().getOwner();
        String file = "%s/%s/%s".formatted(sources.toString().replace('\\', '/'),
                owner.getPackageName().replace('.', '/'), owner.getSourceCodeLocation().getSourceFileName());
        return "[`%s#%s`](%s)".formatted(owner.getSimpleName(), n.method().getName(), file);
    }

    private StaticFlowDocs() {
    }
}
